function googleCover(isbn: string) {
  return {
    url: `https://books.google.com/books?vid=ISBN${isbn}&printsec=frontcover&img=1&zoom=1`,
    sourceUrl: `https://books.google.com/books?vid=ISBN${isbn}`,
  };
}

function hoepliCover(isbn: string) {
  const url = `https://copertine.hoepli.it/archivio/${isbn.slice(0, 3)}/${isbn.slice(3, 7)}/${isbn}.jpg`;
  return { url, sourceUrl: url };
}

